-- Funcion que devuelve, como texto SQL, la estructura completa de la base (tablas, claves, indices, funciones, vistas, triggers, RLS y politicas).
-- La usa el servidor cada noche para guardar el esquema junto a los datos: con las dos cosas se reconstruye todo en cualquier proyecto nuevo.
-- Solo la puede ejecutar la clave de servidor (service_role).
create or replace function public.halo_esquema()
returns text
language sql
security definer
set search_path = public, pg_catalog
as $f$
with ext as (
  select 1 as o, 'create extension if not exists ' || quote_ident(e.extname) || ' with schema ' || quote_ident(n.nspname) || ';' as s
  from pg_extension e join pg_namespace n on n.oid = e.extnamespace
  where e.extname not in ('plpgsql','pg_graphql','pg_stat_statements','pgcrypto','uuid-ossp','supabase_vault')
),
seq as (
  select 2, 'create sequence if not exists public.' || quote_ident(c.relname) || ';'
  from pg_class c where c.relkind = 'S' and c.relnamespace = 'public'::regnamespace
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype in ('i','a'))
),
tbl as (
  select 3, 'create table if not exists public.' || quote_ident(cl.relname) || E' (\n' ||
    string_agg('  ' || quote_ident(a.attname) || ' ' || format_type(a.atttypid, a.atttypmod)
      || case when a.attidentity = 'a' then ' generated always as identity' when a.attidentity = 'd' then ' generated by default as identity' else '' end
      || case when a.attnotnull then ' not null' else '' end
      || case when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(d.adbin, d.adrelid) || ') stored' else coalesce(' default ' || pg_get_expr(d.adbin, d.adrelid), '') end, E',\n' order by a.attnum) || E'\n);'
  from pg_class cl
  join pg_attribute a on a.attrelid = cl.oid and a.attnum > 0 and not a.attisdropped
  left join pg_attrdef d on d.adrelid = cl.oid and d.adnum = a.attnum
  where cl.relnamespace = 'public'::regnamespace and cl.relkind in ('r','p')
  group by cl.relname
),
con as (
  select case when co.contype = 'f' then 5 else 4 end, 'alter table public.' || quote_ident(cl.relname) || ' add constraint ' || quote_ident(co.conname) || ' ' || pg_get_constraintdef(co.oid) || ';'
  from pg_constraint co join pg_class cl on cl.oid = co.conrelid
  where co.connamespace = 'public'::regnamespace and co.contype in ('p','u','c','f')
),
idx as (
  select 6, indexdef || ';' from pg_indexes
  where schemaname = 'public' and indexname not in (select conname from pg_constraint where connamespace = 'public'::regnamespace)
),
fn as (
  select 7, pg_get_functiondef(p.oid) || ';' from pg_proc p
  where p.pronamespace = 'public'::regnamespace and p.prokind = 'f'
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
),
vw as (
  select 8, 'create or replace view public.' || quote_ident(c.relname) || coalesce(' with (' || array_to_string(c.reloptions, ',') || ')', '') || ' as ' || pg_get_viewdef(c.oid, true)
  from pg_class c where c.relkind = 'v' and c.relnamespace = 'public'::regnamespace
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'e')
),
trg as (
  select 9, pg_get_triggerdef(t.oid) || ';' from pg_trigger t join pg_class c on c.oid = t.tgrelid
  where not t.tgisinternal and c.relnamespace = 'public'::regnamespace
),
rls as (
  select 10, 'alter table public.' || quote_ident(relname) || ' enable row level security;' from pg_class
  where relnamespace = 'public'::regnamespace and relkind = 'r' and relrowsecurity
),
pol as (
  select 11, 'create policy ' || quote_ident(policyname) || ' on public.' || quote_ident(tablename) || ' as ' || permissive || ' for ' || cmd || ' to ' || array_to_string(roles, ',')
    || coalesce(' using (' || qual || ')', '') || coalesce(' with check (' || with_check || ')', '') || ';'
  from pg_policies where schemaname = 'public'
)
select 'set check_function_bodies = false;' || E'\n\n' || string_agg(s, E'\n\n' order by o) as script
from (select * from ext union all select * from seq union all select * from tbl union all select * from con union all select * from idx
      union all select * from fn union all select * from vw union all select * from trg union all select * from rls union all select * from pol) x(o, s)
$f$;

revoke all on function public.halo_esquema() from public, anon, authenticated;
grant execute on function public.halo_esquema() to service_role;
